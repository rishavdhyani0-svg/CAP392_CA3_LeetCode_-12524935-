// LeetCode Problem 1342
// Title: Number of Steps to Reduce a Number to Zero
// Difficulty: Easy

class Solution {
    public int numberOfSteps(int num) {
        int steps = 0;
        while (num > 0) {
            if (num % 2 == 0) {
                num = num / 2;
            } else {
                num = num - 1;
            }
            steps++;
        }
        return steps;
    }
}